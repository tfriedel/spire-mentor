"""Generate `static_tables` for one game build from its C# decompilation (e2e WP1).

`derive(decomp)` applies the rules `tests/test_combat_ctx.py` pins the
v0.107.1 tables with:

* `CARD_TYPE`: each card class's `CardType` argument to `CardModel`'s base
  constructor, keyed by the engine's registry name (`CLASS_ALIASES` where the
  CamelCase rule misses, `SKIPPED_CLASSES` dropped).
* `SHOW_COUNTER_RELICS`: the relic classes that override `ShowCounter` with
  anything but a literal `false`.

On v0.107.1 it reproduces `static_tables.CARD_TYPE` and `SHOW_COUNTER_RELICS`
exactly (`tests/e2e/test_e2e_static_tables.py`). For v0.111.0 it writes
`static_tables_v0111.py`:

    python -m ppo.combat_ctx.static_tables_gen v0.111.0 [--check]

`--check` writes nothing and exits 1 if the committed module differs. The
decompilation lives in the sibling `sts2-wiki` checkout and is not exported, so
both modes need it present.
"""

from __future__ import annotations

import argparse
import glob
import os
import re
import sys
from pathlib import Path

from .static_tables import CLASS_ALIASES, SKIPPED_CLASSES

# Monorepo root: python/ppo/combat_ctx/ -> sts2-pycli -> root.
_ROOT = Path(__file__).resolve().parents[4]
# The builds this module generates, and the module each one goes to.
MODULES = {"v0.111.0": "static_tables_v0111"}
_NEVER = re.compile(r"override bool ShowCounter\s*=>\s*false\s*;")
_TYPE = re.compile(r":\s*base\(\s*-?\d+\s*,\s*CardType\.(\w+)")


def decomp_dir(version: str) -> str:
    """The decompilation of `version` in the sibling `sts2-wiki` checkout."""
    return os.path.join(_ROOT, "sts2-wiki", "decompiled", version)


def _classes(decomp: str, package: str) -> dict[str, str]:
    """Class name -> source of every `*.Sts2.Core.Models.<package>/*.cs`."""
    out = {}
    for path in sorted(glob.glob(os.path.join(decomp, f"*.Sts2.Core.Models.{package}", "*.cs"))):
        with open(path, encoding="utf-8") as f:
            out[os.path.basename(path)[:-3]] = f.read()
    return out


def derive(decomp: str) -> tuple[dict[str, str], frozenset[str]]:
    """`(CARD_TYPE, SHOW_COUNTER_RELICS)` of the build decompiled at `decomp`.

    Raises:
        FileNotFoundError: `decomp` has no card or relic classes.
        KeyError: A class has no engine registry name.
        ValueError: A card class names no `CardType`.
    """
    import sts2_rs

    from ppo import vocab

    cards, relics = _classes(decomp, "Cards"), _classes(decomp, "Relics")
    if not cards or not relics:
        raise FileNotFoundError(f"no card or relic classes under {decomp}")
    canon: dict[str, str] = {}
    for name in sts2_rs.list_registry_names("card"):
        canon.setdefault(vocab.canonical(name), name)
    card_type = {}
    for cls, src in cards.items():
        if cls in SKIPPED_CLASSES:
            continue
        m = _TYPE.search(src)
        if m is None:
            raise ValueError(f"{cls}: no CardType in its base constructor call")
        card_type[CLASS_ALIASES.get(cls) or canon[vocab.canonical(cls)]] = m.group(1)
    rcanon = {vocab.canonical(n): n for n in sts2_rs.list_registry_names("relic")}
    show = frozenset(
        rcanon[vocab.canonical(cls)]
        for cls, src in relics.items()
        if "override bool ShowCounter" in src and not _NEVER.search(src)
    )
    return dict(sorted(card_type.items())), show


def render(version: str, card_type: dict[str, str], show: frozenset[str]) -> str:
    """The source of the generated module for `version`."""
    lines = [
        f'"""Pinned static tables for the combat context net, {version} (e2e WP1).',
        "",
        f"Generated by `python -m ppo.combat_ctx.static_tables_gen {version}` from the",
        f"{version} C# decompilation in `sts2-wiki`; do not edit by hand. `static_tables`",
        "describes the tables and selects one per game version.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "CARD_TYPE: dict[str, str] = {",
        *(f'    "{k}": "{v}",' for k, v in sorted(card_type.items())),
        "}",
        "SHOW_COUNTER_RELICS: frozenset[str] = frozenset(",
        "    {",
        *(f'        "{r}",' for r in sorted(show)),
        "    }",
        ")",
    ]
    return "\n".join(lines) + "\n"


def module_path(version: str) -> Path:
    return Path(__file__).with_name(f"{MODULES[version]}.py")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("version", choices=sorted(MODULES))
    ap.add_argument("--check", action="store_true", help="exit 1 if the module is stale")
    args = ap.parse_args(argv)
    decomp = decomp_dir(args.version)
    if not os.path.isdir(decomp):
        print(f"no decompilation at {decomp}", file=sys.stderr)
        return 2
    text = render(args.version, *derive(decomp))
    path = module_path(args.version)
    if args.check:
        same = path.exists() and path.read_text(encoding="utf-8") == text
        print(f"{path.name}: {'up to date' if same else 'STALE'}")
        return 0 if same else 1
    path.write_text(text, encoding="utf-8")
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
