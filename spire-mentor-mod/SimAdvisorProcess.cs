// SimAdvisorProcess.cs -- phase 8: auto-launch the Python advisor backend.
//
// When the mode flips to Advisor (and AdvisorAutoLaunch is on, and no
// bridge client is already connected), launches the advisor process and
// keeps the HUD status chip honest about its state (launching / crashed
// with exit code). Stopped when the mode leaves Advisor and on game exit
// (SimShutdown), and -- for the exit paths that never reach managed code --
// killed by the OS via SimJobObject.
//
// Command resolution:
//   1. SpireMentorModConfig.AdvisorCommand (settings page), if non-empty --
//      run via `cmd.exe /c <command>`.
//   2. Otherwise `SimAdvisor.cmd` next to SpireMentor.dll -- generated by the
//      csproj deploy target with this repo's sts2-pycli path baked in, so a
//      normal dev deploy needs zero configuration.
//   3. Otherwise `SimAdvisor\SimAdvisor.exe` next to SpireMentor.dll -- the
//      packaged torch-free advisor (GH #380) shipped in the distribution
//      zip; launched directly, no cmd.exe wrapper.
//
// The .cmd outranks the packaged exe because it exists ONLY on a machine
// that ran the dev deploy, which is the stronger statement of intent: a
// packaged install never has one, while a dev box acquires a leftover
// `SimAdvisor\` the moment it tests the zip once -- and probing the exe
// first then froze every later live session against a stale snapshot while
// `dotnet build` went on redeploying the .cmd. Both present is logged.
//
// Every branch passes `--port <SimConfig.port>` (so the advisor cannot
// silently listen on a different port than the mod serves) and an explicit
// `--log-dir` under %LOCALAPPDATA%\SpireMentor.
//
// stdout/stderr are appended to `advisor_stdout.log` (`advisor_stdout.<port>.log`
// off the default port; see StdoutLogPath) under
// %LOCALAPPDATA%\SpireMentor (the MCTS backend is chatty; piping it into
// godot.log would bury everything, and the mod dir is Program Files on a
// default Steam install -- not user-writable).

using System;
using System.Diagnostics;
using System.IO;
using System.Reflection;
using System.Threading.Tasks;

namespace SpireMentor;

internal static class SimAdvisorProcess
{
    private static readonly object _lock = new();
    private static Process? _process;
    /// <summary>
    /// Per-launch "we killed it on purpose" flag. It must NOT be one shared
    /// bool: output/exit monitoring completes asynchronously, so toggling advisor mode
    /// off and straight back on let the OLD process's exit handler read the
    /// NEW launch's reset flag and report a phantom "advisor: crashed"
    /// (seen 2026-08-05 on an F8 toggle).
    /// </summary>
    private sealed class StopFlag { public bool Value; }

    private static StopFlag? _stopFlag;

    public static void EnsureStarted()
    {
        lock (_lock)
        {
            if (_process is { HasExited: false })
            {
                return;
            }
            if (!SpireMentorModConfig.AdvisorAutoLaunch)
            {
                Logger.Log("[SimAdvisorProcess] Auto-launch disabled in settings.");
                return;
            }
            if (BridgeServer.Instance.Port == 0)
            {
                // Nothing is listening here, so an advisor launched against
                // the configured port would serve whichever game owns it
                // (another instance on this machine).
                Logger.Log("[SimAdvisorProcess] The bridge is not listening; not launching an advisor.");
                SimHud.Instance.SetAdvisorStatus(SimAdvisorStatus.Crashed);
                return;
            }
            if (BridgeServer.Instance.IsClientConnected)
            {
                // A backend (or a manually started advisor) is already
                // attached; don't spawn a competitor for the single slot.
                //
                // Say so. This branch used to return in silence, and an
                // advisor process ORPHANED by a previous game (it outlives the
                // game and reconnects to the new one's port) then looked
                // exactly like "the launcher never ran" -- while also making
                // SimRuntime.AutopilotEngaged true at boot, so the game went
                // non-interactive before anyone asked it to (2026-08-06).
                Logger.Log(
                    "[SimAdvisorProcess] A bridge client is already connected; not launching one. " +
                    "If no advisor was started for THIS session, an orphaned one from a previous " +
                    "game is holding the slot -- kill it.");
                return;
            }
            if (!OperatingSystem.IsWindows())
            {
                // Every launcher below goes through cmd.exe or a win64 exe. The
                // Workshop delivers the mod to Mac/Linux too, where a failed
                // launch would otherwise just read "advisor: crashed".
                Logger.Log(
                    "[SimAdvisorProcess] The bundled advisor is Windows-only; not launching it. " +
                    "Start an advisor yourself and point it at the configured port.");
                SimHud.Instance.SetAdvisorStatus(SimAdvisorStatus.Crashed);
                return;
            }

            string? modDir = Path.GetDirectoryName(Assembly.GetExecutingAssembly().Location);
            // --port in EVERY branch: the advisor otherwise defaults to 9002
            // and silently diverges from a non-default SpireMentor.conf port
            // or a fallback port (BridgeServer.StartWithFallback).
            // --log-dir only for the packaged exe below -- the dev lanes keep
            // their historical CWD-relative logs/realgame_advisor (the F7
            // harness and climb tooling read from there).
            string advisorArgs = $"--port {BridgeServer.Instance.Port}";
            int bridgePort = BridgeServer.Instance.Port;
            if (bridgePort != DefaultPort)
            {
                // A second instance's advisor would otherwise also bind the
                // control plane's default 8079, which Windows allows silently;
                // shift it by the same offset as the bridge (9012 -> 8089).
                advisorArgs += $" --control-port {ControlPort(bridgePort)}";
            }
            // Where the bundled workbench's Report button sends (the control
            // plane forwards its /api/bugreport to that site's intake): the same site the
            // mod's own bug reports go to (SimBugReport). None = the button
            // saves reports to a file beside the advisor's logs.
            string? bugSite = SimBugReport.Site;
            if (bugSite != null && bugSite.IndexOfAny(new[] { ' ', '"' }) < 0)
            {
                advisorArgs += $" --bug-report-site {bugSite}";
            }
            if (SimConfig.Instance.AdvisorAutoplay)
            {
                // Unattended lane (climb / F7 harness): never auto-spawn the
                // workbench web server -- nobody is watching a browser, and a
                // sweep must stay byte-identical to its historical behavior.
                advisorArgs += " --workbench off";
            }
            // Opt-in for the browser-only workbench (GH #709): the origin
            // the control plane may answer with CORS + Private Network
            // Access headers. Blank keeps the control plane proxy-only.
            string browserOrigin = SpireMentorModConfig.BrowserWorkbenchOrigin.Trim();
            if (browserOrigin.Length > 0 && browserOrigin.IndexOfAny(new[] { ' ', '"' }) < 0)
            {
                advisorArgs += $" --control-allow-origin {browserOrigin}";
            }
            ProcessStartInfo psi;
            string command = SpireMentorModConfig.AdvisorCommand;
            if (!string.IsNullOrWhiteSpace(command))
            {
                // Settings-page override. Our args append after the command's
                // own, and argparse takes the last occurrence -- so the port
                // always follows SpireMentor.conf, the single source of truth
                // for which port both sides use.
                psi = new ProcessStartInfo
                {
                    FileName = "cmd.exe",
                    Arguments = $"/c {command} {advisorArgs}",
                };
            }
            else
            {
                string exe = modDir != null
                    ? Path.Combine(modDir, "SimAdvisor", "SimAdvisor.exe")
                    : "";
                string script = modDir != null ? Path.Combine(modDir, "SimAdvisor.cmd") : "";
                bool haveScript = File.Exists(script);
                bool haveExe = File.Exists(exe);
                if (haveScript && haveExe)
                {
                    // Say which one wins. Silence here reads as "my fix did not
                    // work": the loser is a whole separate copy of the advisor.
                    Logger.Log(
                        $"[SimAdvisorProcess] Both launchers exist; using the dev {script} and " +
                        $"IGNORING the packaged {exe}. Delete the SimAdvisor directory to run the " +
                        "packaged advisor, or the .cmd to stop it winning.");
                }
                if (haveScript)
                {
                    // Dev path: the deploy-generated .cmd forwards %* to the
                    // advisor, so our args ride through.
                    psi = new ProcessStartInfo
                    {
                        FileName = "cmd.exe",
                        Arguments = $"/c \"{script}\" {advisorArgs}",
                    };
                }
                else if (haveExe)
                {
                    // Packaged advisor (GH #380): direct launch, no cmd.exe.
                    // Explicit --log-dir keeps JSONL logs out of the install
                    // dir even if the exe's own frozen default ever drifts.
                    psi = new ProcessStartInfo
                    {
                        FileName = exe,
                        Arguments = advisorArgs +
                            $" --log-dir \"{Path.Combine(AppDataDir(), "logs", "realgame_advisor")}\"",
                        WorkingDirectory = Path.GetDirectoryName(exe),
                    };
                }
                else
                {
                    Logger.Log(
                        "[SimAdvisorProcess] No advisor command configured, no SimAdvisor.cmd and no " +
                        "SimAdvisor\\SimAdvisor.exe next to the DLL (re-run the SpireMentor deploy or " +
                        "reinstall the mod zip, or set the command on the settings page). " +
                        "Advisor must be started manually.");
                    return;
                }
            }
            TextWriter? logWriter = null;
            WindowsChildProcess? child = null;
            try
            {
                string logPath = StdoutLogPath(BridgeServer.Instance.Port);
                RotateOversizedLog(logPath);
                var stopFlag = new StopFlag();
                // Shared, and closed when the process exits: Kill() returns
                // before the old process's output monitor finishes, so an F8
                // off -> on found the previous launch's writer still holding
                // the file and the relaunch failed with "being used by
                // another process" (seen 2026-10-17, v0.5.0).
                logWriter = TextWriter.Synchronized(new StreamWriter(new FileStream(
                    logPath, FileMode.Append, FileAccess.Write, FileShare.ReadWrite | FileShare.Delete)));
                logWriter.WriteLine($"--- advisor launched {DateTime.Now:yyyy-MM-dd HH:mm:ss} ---");
                child = WindowsChildProcess.Start(psi.FileName, psi.Arguments, psi.WorkingDirectory,
                    process => SimJobObject.Adopt(process));
                Process process = child.Process;
                _stopFlag = stopFlag;
                // The advisor's MCTS competes with the game's render loop
                // for this machine; the search is the one on the critical
                // path (the game is idle while it thinks — SimThinkFps.cs).
                // AboveNormal biases the scheduler its way. Direct children
                // only (cmd.exe on the dev path — the grandchild python
                // inherits nothing), so this is best-effort next to the
                // think-time FPS cap, not the mechanism.
                try
                {
                    process.PriorityClass = ProcessPriorityClass.AboveNormal;
                }
                catch (Exception prioEx)
                {
                    Logger.Log($"[SimAdvisorProcess] Could not raise advisor priority: {prioEx.Message}");
                }
                _process = process;
                Logger.Log($"[SimAdvisorProcess] Launched advisor (pid {process.Id}); output -> {logPath}");
                SimHud.Instance.SetAdvisorStatus(SimAdvisorStatus.Launching);
                _ = MonitorAsync(child, logWriter, stopFlag);
            }
            catch (Exception ex)
            {
                if (child != null)
                {
                    try
                    {
                        if (!child.Process.HasExited)
                        {
                            child.Process.Kill(entireProcessTree: true);
                        }
                    }
                    catch (Exception cleanupEx)
                    {
                        Logger.Log($"[SimAdvisorProcess] Failed to stop partially launched advisor: {cleanupEx}");
                    }
                    child.Dispose();
                }
                CloseOutput(child: null, logWriter);
                Logger.Log($"[SimAdvisorProcess] Launch failed: {ex.Message}");
                SimHud.Instance.SetAdvisorStatus(SimAdvisorStatus.Crashed);
                _process = null;
            }
        }
    }

    private static async Task MonitorAsync(WindowsChildProcess child, TextWriter logWriter, StopFlag stopFlag)
    {
        int code = -1;
        try
        {
            await Task.WhenAll(
                ReadOutputAsync(child.StandardOutput, logWriter),
                ReadOutputAsync(child.StandardError, logWriter),
                child.Process.WaitForExitAsync()).ConfigureAwait(false);
            code = child.Process.ExitCode;
            TryWrite(logWriter, $"--- advisor exited ({code}) ---");
        }
        catch (Exception ex)
        {
            Logger.Log($"[SimAdvisorProcess] Advisor output/exit monitoring failed: {ex}");
        }
        finally
        {
            lock (_lock)
            {
                // A stopped advisor may finish draining after its replacement starts.
                if (ReferenceEquals(_process, child.Process))
                {
                    _process = null;
                    if (!stopFlag.Value)
                    {
                        Logger.Log($"[SimAdvisorProcess] Advisor process exited unexpectedly (code {code}).");
                        SimHud.Instance.SetAdvisorStatus(SimAdvisorStatus.Crashed);
                    }
                }
            }
            CloseOutput(child, logWriter);
        }
    }

    private static void CloseOutput(WindowsChildProcess? child, TextWriter? logWriter)
    {
        try
        {
            logWriter?.Dispose();
        }
        catch (IOException ex)
        {
            Logger.Log($"[SimAdvisorProcess] Could not close advisor log: {ex}");
        }
        finally
        {
            child?.Dispose();
        }
    }

    private static async Task ReadOutputAsync(StreamReader reader, TextWriter logWriter)
    {
        while (await reader.ReadLineAsync().ConfigureAwait(false) is { } line)
        {
            TryWrite(logWriter, line);
            NoteBuildProgress(line);
        }
    }

    public static void Stop()
    {
        lock (_lock)
        {
            if (_stopFlag != null)
            {
                _stopFlag.Value = true;
            }
            if (_process is { HasExited: false })
            {
                try
                {
                    // Kill the whole tree: the cmd.exe wrapper's Python
                    // child (dev) and any PyInstaller bootloader child
                    // (packaged exe) die with it.
                    _process.Kill(entireProcessTree: true);
                    Logger.Log("[SimAdvisorProcess] Advisor process stopped.");
                }
                catch (Exception ex)
                {
                    Logger.Log($"[SimAdvisorProcess] Stop failed: {ex.Message}");
                }
            }
            _process = null;
        }
    }

    /// <summary>
    /// <c>advisor_stdout.log</c>, or <c>advisor_stdout.&lt;port&gt;.log</c> off the
    /// default port. A second game instance on the same machine (the local
    /// co-op lane, or a port fallback) launches its own advisor; two writers
    /// appending to one file each keep their own position and overwrite each
    /// other, so one advisor's output was lost (2026-10-23 co-op batch).
    /// </summary>
    internal static string StdoutLogPath(int port) =>
        Path.Combine(AppDataDir(), port == 0 || port == DefaultPort
            ? "advisor_stdout.log"
            : $"advisor_stdout.{port}.log");

    private const int DefaultPort = 9002;
    private const int DefaultControlPort = 8079;

    /// <summary>The advisor's control-plane port for a bridge port: the
    /// default 8079, shifted by the bridge's offset from 9002 (the
    /// `--control-port` every launch above passes).</summary>
    internal static int ControlPort(int bridgePort) =>
        bridgePort == 0 || bridgePort == DefaultPort
            ? DefaultControlPort
            : DefaultControlPort + bridgePort - DefaultPort;

    /// <summary>
    /// %LOCALAPPDATA%\SpireMentor -- the one user-writable home for advisor
    /// logs and (packaged installs) SpireMentor.conf. The mod dir itself is
    /// Program Files on a default Steam install.
    /// </summary>
    internal static string AppDataDir()
    {
        string dir = Path.Combine(
            Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData),
            "SpireMentor");
        Directory.CreateDirectory(dir);
        return dir;
    }

    /// <summary>
    /// The stdout log is append-forever (each launch adds a banner); before
    /// it moved out of the mod dir it had grown past 4 MB unnoticed. Once it
    /// passes 10 MB, ROTATE it to <c>advisor_stdout.log.1</c> and start a
    /// fresh file.
    /// </summary>
    /// <remarks>
    /// Rotate, never delete. tools/ascension_climb.py archives each run's
    /// p_win/q evidence as a BYTE SLICE of this file (its
    /// <c>archive_repro</c> seeks to an offset captured before the launch),
    /// so deleting it mid-climb wrote a 0-byte artifact for that run while
    /// still reporting it as archived. The Python side detects the rotation
    /// and reads across both files -- which only works while the old bytes
    /// still exist.
    /// </remarks>
    private static void RotateOversizedLog(string logPath)
    {
        try
        {
            var info = new FileInfo(logPath);
            if (info.Exists && info.Length > 10 * 1024 * 1024)
            {
                File.Move(logPath, logPath + ".1", overwrite: true);
            }
        }
        catch
        {
            // Locked or already gone; the StreamWriter append will cope.
        }
    }

    /// <summary>
    /// Turn `uv`'s build chatter into a status the player can actually see.
    ///
    /// The dev launcher runs the advisor through `uv run`, whose cache-keys
    /// span the Rust workspace, so any `.rs`/`Cargo.*` edit makes the NEXT
    /// launch compile `sts2_rs` first. That is correct and deliberate (it is
    /// what stops a stale wheel serving old engine code), but a cold rebuild
    /// measured ~14 minutes during which the advisor prints one line, opens no
    /// port and answers nothing.
    ///
    /// With the HUD stuck on "launching" that is indistinguishable from a hang:
    /// on 2026-08-22 three launches were each killed by quitting the game
    /// (SimJobObject takes the build down with it), so the build never finished
    /// and every session started it again from the same place. Naming it — and
    /// saying it is minutes, not seconds — is what makes waiting the obvious
    /// move.
    /// </summary>
    private static void NoteBuildProgress(string line)
    {
        // uv prints "   Building sts2-rs @ file:///…" then "      Built sts2-rs @ …".
        // Matched loosely: the surrounding whitespace and the URL both vary.
        bool started = line.Contains("Building sts2-rs");
        bool finished = line.Contains("Built sts2-rs");
        if (!started && !finished)
        {
            return;
        }
        try
        {
            if (finished)
            {
                // Checked first: "Built" also contains no "Building", but keep
                // the order explicit so a future "Rebuilding…" cannot invert it.
                SimHud.Instance.SetAdvisorStatus(SimAdvisorStatus.Launching);
                SimActionLog.Note("Engine build finished — starting the advisor.");
                Logger.Log("[SimAdvisorProcess] sts2_rs build finished.");
                return;
            }
            SimHud.Instance.SetAdvisorStatus(SimAdvisorStatus.Building);
            SimActionLog.Note(
                "Building the Rust engine — first advisor launch after an engine change. " +
                "This takes MINUTES (~14 on a cold build); leave the game running or the " +
                "build is killed and starts over. Pre-build it with `just advisor-warm` " +
                "in sts2-pycli to skip this wait.");
            Logger.Log("[SimAdvisorProcess] sts2_rs build started; advisor cannot connect until it finishes.");
        }
        catch (Exception ex)
        {
            // A status chip must never take the advisor down with it.
            Logger.Log($"[SimAdvisorProcess] Build-progress note failed: {ex.Message}");
        }
    }

    private static void TryWrite(TextWriter writer, string line)
    {
        try
        {
            writer.WriteLine(line);
            writer.Flush();
        }
        catch
        {
            // log file gone/locked; never disturb the game
        }
    }
}
