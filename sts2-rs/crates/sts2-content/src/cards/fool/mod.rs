/// Whether `id` is one of The Fool's cards ([`FOOL_CARDS`]).
#[must_use]
pub fn is_fool_card(id: CardId) -> bool {
    FOOL_CARDS.contains(&id)
}

/// Register every Fool play handler. Called from
/// [`crate::cards::dispatch::install_default_registry`].
pub fn install_pool() {
    card_effects::register_many(POOL);
    for id in FOOL_CARDS {
        if powers::self_power(id).is_some() {
            card_effects::register(id, powers::play_self_power as PlayCardFn);
        }
    }
}

